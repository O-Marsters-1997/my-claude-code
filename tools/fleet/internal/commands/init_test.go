func newRepo(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for name, content := range files {
		p := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	for _, args := range [][]string{{"init", "-q", "-b", "main"}, {"add", "-A"}} {
		cmd := exec.Command("git", args...)
		cmd.Dir = dir
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v\n%s", args, err, out)
		}
	}
	return dir
}

func runFleet(t *testing.T, args ...string) (stdout, stderr string, err error) {
	t.Helper()
	var out, errw bytes.Buffer
	root := &cli.Command{Name: "fleet", Writer: &out, ErrWriter: &errw, Commands: commands.Router()}
	err = root.Run(context.Background(), append([]string{"fleet"}, args...))
	return out.String(), errw.String(), err
}

var initFixture = map[string]string{
	"justfile":                    "lint:\n    x\ntest:\n    go test ./...\ncss:\n    tailwindcss -o web/app.css\n",
	"web/app.css":                 ".a{}",
	"internal/db/db.go":           "// Code generated by sqlc. DO NOT EDIT.\npackage db\n",
	"internal/gen/unmapped.pb.go": "// Code generated by protoc. DO NOT EDIT.\npackage gen\n",
}

func TestInitDryRunPrintsOnlyTOML(t *testing.T) {
	dir := newRepo(t, initFixture)

	stdout, stderr, err := runFleet(t, "init", "--dry-run", "--repo", dir)
	if err != nil {
		t.Fatal(err)
	}

	var got config.Config
	if _, err := toml.Decode(stdout, &got); err != nil {
		t.Fatalf("stdout is not TOML: %v\n%s", err, stdout)
	}
	want := config.Config{
		CI:     "off",
		Checks: config.Checks{PrePush: []string{"just lint", "just test", "just css"}, Suite: []string{"just test"}},
		Regen:  map[string]string{"web/app.css": "just css"},
	}
	if diff := cmp.Diff(want, got); diff != "" {
		t.Errorf("config (-want +got):\n%s", diff)
	}
	if !strings.Contains(stderr, "internal/db/**") || !strings.Contains(stderr, "internal/gen/**") {
		t.Errorf("stderr = %q, want unmapped generated paths named", stderr)
	}
	if _, err := os.Stat(filepath.Join(dir, ".claude", "fleet.toml")); err == nil {
		t.Error("dry run wrote .claude/fleet.toml")
	}
}

func TestInitWritesAndRefusesToOverwrite(t *testing.T) {
	dir := newRepo(t, initFixture)

	stdout, _, err := runFleet(t, "init", "--repo", dir)
	if err != nil {
		t.Fatal(err)
	}
	if stdout != "wrote .claude/fleet.toml\n" {
		t.Errorf("stdout = %q", stdout)
	}
	if _, err := os.Stat(filepath.Join(dir, ".claude", "fleet.toml")); err != nil {
		t.Errorf("fleet.toml not written: %v", err)
	}

	if _, _, err := runFleet(t, "init", "--repo", dir); err == nil {
		t.Error("second init without --force succeeded, want error")
	}
	if _, _, err := runFleet(t, "init", "--force", "--repo", dir); err != nil {
		t.Errorf("init --force: %v", err)
	}
}
