func TestMeasureDropsSlowAndFailingChecks(t *testing.T) {
	opts := detect.Options{Measure: func(cmd string) (time.Duration, error) {
		switch cmd {
		case "just vet":
			return 0, errors.New("boom")
		case "just test":
			return 90 * time.Second, nil
		}
		return time.Second, nil
	}}
	res := scan(fstest.MapFS{"justfile": file("lint:\n    x\ntest:\n    x\nvet:\n    x\n")}, opts)

	if diff := cmp.Diff([]string{"just lint"}, res.Config.Checks.PrePush); diff != "" {
		t.Errorf("pre_push (-want +got):\n%s", diff)
	}
}

func TestCIJobsWithoutLocalEquivalent(t *testing.T) {
	workflow := "name: ci\njobs:\n  lint:\n    runs-on: x\n  e2e-browser:\n    runs-on: x\n"
	res := scan(fstest.MapFS{
		"justfile":                 file("lint:\n    x\n"),
		".github/workflows/ci.yml": file(workflow),
	}, detect.Options{})

	want := "CI jobs with no local equivalent: e2e-browser"
	if got := res.Notes[len(res.Notes)-1]; got != want {
		t.Errorf("last note = %q, want %q", got, want)
	}
}

func TestRegenFromGeneratedHeaders(t *testing.T) {
	res := scan(fstest.MapFS{
		"justfile":                   file("generate:\n    sqlc generate\n"),
		"internal/store/db/db.go":    file("// Code generated by sqlc. DO NOT EDIT.\npackage db\n"),
		"internal/store/db/q.sql.go": file("// Code generated by sqlc. DO NOT EDIT.\npackage db\n"),
		"internal/mixed/gen.go":      file("// @generated\npackage mixed\n"),
		"internal/mixed/hand.go":     file("package mixed\n"),
		"main.go":                    file("package main\n"),
	}, detect.Options{})

	want := map[string]string{
		"internal/store/db/**":  "just generate",
		"internal/mixed/gen.go": "just generate",
	}
	if diff := cmp.Diff(want, res.Config.Regen); diff != "" {
		t.Errorf("regen (-want +got):\n%s", diff)
	}
}

func TestRegenFromGeneratorConfigAndGoGenerate(t *testing.T) {
	configOnly := scan(fstest.MapFS{
		"sqlc.yaml": file("version: 2\n"),
		"db/db.go":  file("// Code generated by sqlc. DO NOT EDIT.\npackage db\n"),
	}, detect.Options{})
	if diff := cmp.Diff(map[string]string{"db/**": "sqlc generate"}, configOnly.Config.Regen); diff != "" {
		t.Errorf("sqlc regen (-want +got):\n%s", diff)
	}

	directive := scan(fstest.MapFS{
		"a.go":        file("package a\n\n//go:generate stringer -type=X\n"),
		"x_string.go": file("// Code generated by \"stringer\"; DO NOT EDIT.\npackage a\n"),
	}, detect.Options{})
	if diff := cmp.Diff(map[string]string{"x_string.go": "go generate ./..."}, directive.Config.Regen); diff != "" {
		t.Errorf("go:generate regen (-want +got):\n%s", diff)
	}
}

