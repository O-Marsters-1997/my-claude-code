func scan(files fstest.MapFS, opts detect.Options) detect.Result {
	tracked := make([]string, 0, len(files))
	for name := range files {
		tracked = append(tracked, name)
	}
	sort.Strings(tracked)
	return detect.Scan(files, tracked, opts)
}

func file(content string) *fstest.MapFile { return &fstest.MapFile{Data: []byte(content)} }

func TestPrePushFromJustfile(t *testing.T) {
	res := scan(fstest.MapFS{"justfile": file("set shell := [\"bash\"]\n\nlint:\n    golangci-lint run\n\ntest:\n    go test ./...\n\ndeploy:\n    ./deploy.sh\n")}, detect.Options{})

	want := []string{"just lint", "just test"}
	if diff := cmp.Diff(want, res.Config.Checks.PrePush); diff != "" {
		t.Errorf("pre_push (-want +got):\n%s", diff)
	}
	if diff := cmp.Diff([]string{"just test"}, res.Config.Checks.Suite); diff != "" {
		t.Errorf("suite (-want +got):\n%s", diff)
	}
	if diff := cmp.Diff([]string{"Left out of pre_push (slow or not a quick check): just deploy"}, res.Notes); diff != "" {
		t.Errorf("notes (-want +got):\n%s", diff)
	}
}

