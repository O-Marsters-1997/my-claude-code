func TestUnmappedGeneratedPathsAreReported(t *testing.T) {
	res := scan(fstest.MapFS{
		"gen/a.go": file("// Code generated by hand. DO NOT EDIT.\npackage gen\n"),
		"b.pb.go":  file("// Code generated by protoc. DO NOT EDIT.\npackage b\n"),
	}, detect.Options{})

	if diff := cmp.Diff([]string{"b.pb.go", "gen/**"}, res.Unmapped); diff != "" {
		t.Errorf("unmapped (-want +got):\n%s", diff)
	}
	if len(res.Config.Regen) != 0 {
		t.Errorf("regen = %v, want empty", res.Config.Regen)
	}
}
