#!/usr/bin/env bash
# Run: hooks/require-go-skills.test.sh
set -u
HOOK="$(cd "$(dirname "$0")" && pwd)/require-go-skills.sh"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
fails=0

mkdir -p "$TMP/mod/.claude/skills/testing-policy" "$TMP/plain" "$TMP/nomod"
touch "$TMP/mod/go.mod" "$TMP/plain/go.mod" "$TMP/mod/.claude/skills/testing-policy/SKILL.md"
for d in mod plain; do git -C "$TMP/$d" init -q; done
printf 'package a\n' >"$TMP/mod/a.go"
printf 'package a\n' >"$TMP/mod/a_test.go"
printf 'package a\n' >"$TMP/plain/a_test.go"
printf 'package a\n' >"$TMP/nomod/a.go"
printf '// Code generated by sqlc. DO NOT EDIT.\npackage a\n' >"$TMP/mod/gen.go"
mkdir -p "$TMP/mod/vendor/x"
printf 'package x\n' >"$TMP/mod/vendor/x/x.go"

skill_call() { printf '{"message":{"role":"assistant","content":[{"type":"tool_use","name":"Skill","input":{"skill":"%s"}}]}}\n' "$1"; }
slash_cmd() { printf '{"message":{"role":"user","content":"<command-name>/%s</command-name>"}}\n' "$1"; }
mention() { printf '{"message":{"role":"user","content":"please remember go-idiomatic and testing-policy"}}\n'; }

T_NONE="$TMP/none.jsonl"
T_MENTION="$TMP/mention.jsonl"
T_GO="$TMP/go.jsonl"
T_SLASH="$TMP/slash.jsonl"
T_BOTH="$TMP/both.jsonl"
: >"$T_NONE"
mention >"$T_MENTION"
skill_call go-idiomatic >"$T_GO"
slash_cmd go-idiomatic >"$T_SLASH"
{ skill_call go-idiomatic; skill_call testing-policy; } >"$T_BOTH"

payload() {
	jq -nc --arg f "$1" --arg t "$2" --arg tool "${3:-Edit}" \
		'{tool_name: $tool, tool_input: {file_path: $f, content: "package a\n"}, transcript_path: $t, session_id: "s"}'
}

check() {
	local name=$1 want=$2 input=$3
	shift 3
	local err code
	err=$(env "$@" "$HOOK" <<<"$input" 2>&1 >/dev/null)
	code=$?
	if [ "$code" != "$want" ]; then
		printf 'FAIL %s: exit %s, want %s\n%s\n' "$name" "$code" "$want" "$err"
		fails=$((fails + 1))
	fi
}

check "non-Go file is ignored" 0 "$(payload "$TMP/mod/README.md" "$T_NONE")" X=1
check "Go file with no skill loaded blocks" 2 "$(payload "$TMP/mod/a.go" "$T_NONE")" X=1
check "mentioning the skill by name does not count" 2 "$(payload "$TMP/mod/a.go" "$T_MENTION")" X=1
check "Skill tool call unblocks" 0 "$(payload "$TMP/mod/a.go" "$T_GO")" X=1
check "slash command unblocks" 0 "$(payload "$TMP/mod/a.go" "$T_SLASH")" X=1
check "Write is gated like Edit" 2 "$(payload "$TMP/mod/a.go" "$T_NONE" Write)" X=1
check "test file needs testing-policy when the project ships it" 2 "$(payload "$TMP/mod/a_test.go" "$T_GO")" X=1
check "both skills loaded unblocks a test file" 0 "$(payload "$TMP/mod/a_test.go" "$T_BOTH")" X=1
check "test file needs only go-idiomatic without a project testing-policy" 0 "$(payload "$TMP/plain/a_test.go" "$T_GO")" X=1
check "generated file is skipped" 0 "$(payload "$TMP/mod/gen.go" "$T_NONE")" X=1
check "vendor is skipped" 0 "$(payload "$TMP/mod/vendor/x/x.go" "$T_NONE")" X=1
check "no go.mod is skipped" 0 "$(payload "$TMP/nomod/a.go" "$T_NONE")" X=1
check "opt-out env is honoured" 0 "$(payload "$TMP/mod/a.go" "$T_NONE")" CC_GO_SKILLS_OFF=1
check "missing transcript fails open" 0 "$(payload "$TMP/mod/a.go" "$TMP/absent.jsonl")" X=1
check "malformed input fails open" 0 "not json" X=1

new_write=$(jq -nc --arg f "$TMP/mod/new_gen.go" --arg t "$T_NONE" \
	'{tool_name: "Write", tool_input: {file_path: $f, content: "// Code generated by x. DO NOT EDIT.\npackage a\n"}, transcript_path: $t}')
check "new generated file via Write is skipped" 0 "$new_write" X=1

[ "$fails" -eq 0 ] && echo "all hook tests passed"
exit "$fails"
