#!/usr/bin/env bash
set -u
HOOK="$(cd "$(dirname "$0")" && pwd)/lint-edited.sh"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
fails=0

check() {
	local name=$1 want=$2 file=$3
	shift 3
	local err code
	err=$(jq -nc --arg f "$file" '{tool_name: "Edit", tool_input: {file_path: $f}}' | env "$@" "$HOOK" 2>&1 >/dev/null)
	code=$?
	if [ "$code" != "$want" ]; then
		printf 'FAIL %s: exit %s, want %s\n%s\n' "$name" "$code" "$want" "$err"
		fails=$((fails + 1))
	fi
}

GO="$TMP/go"
mkdir -p "$GO/a" "$GO/vendor/x"
printf 'module example.com/m\n\ngo 1.22\n' >"$GO/go.mod"
printf 'package a\n\nfunc Add(a, b int) int { return a + b }\n' >"$GO/a/a.go"
printf 'package x\n\nfunc dead() {}\n' >"$GO/vendor/x/x.go"
git -C "$GO" init -q && git -C "$GO" add -A && git -C "$GO" -c user.name=t -c user.email=t@t commit -qm init

if command -v golangci-lint >/dev/null; then
	check "clean Go file passes" 0 "$GO/a/a.go" X=1
	printf 'package a\n\nfunc dead() {}\n' >"$GO/a/dead.go"
	printf '// Code generated by sqlc. DO NOT EDIT.\npackage a\n\nfunc genDead() {}\n' >"$GO/a/gen.go"
	check "new unused Go func blocks" 2 "$GO/a/dead.go" X=1
	check "generated Go file is skipped" 0 "$GO/a/gen.go" X=1
	check "opt-out env skips" 0 "$GO/a/dead.go" CC_LINT_EDITED_OFF=1
else
	echo "skip Go cases: golangci-lint not installed"
fi
check "vendor is skipped" 0 "$GO/vendor/x/x.go" X=1
check "missing file is skipped" 0 "$GO/a/nope.go" X=1
check "other extensions are skipped" 0 "$GO/go.mod" X=1

BIOME=$(command -v biome)
JS="$TMP/js"
mkdir -p "$JS/src" "$JS/node_modules/.bin"
printf '{"linter":{"rules":{"correctness":{"noUnusedImports":"error"}}}}\n' >"$JS/biome.json"
printf 'export const x = 1;\n' >"$JS/src/ok.ts"
printf 'import { y } from "./ok";\nexport const z = 1;\n' >"$JS/src/bad.ts"
mkdir -p "$TMP/nobiome"
printf 'import { y } from "./ok";\n' >"$TMP/nobiome/bad.ts"
check "TS file with no biome.json is skipped" 0 "$TMP/nobiome/bad.ts" X=1
check "TS file with no installed biome is skipped" 0 "$JS/src/bad.ts" X=1

if [ -n "$BIOME" ]; then
	ln -s "$BIOME" "$JS/node_modules/.bin/biome"
	check "clean TS file passes" 0 "$JS/src/ok.ts" X=1
	check "unused import blocks" 2 "$JS/src/bad.ts" X=1
else
	echo "skip Biome cases: biome not on PATH"
fi

[ "$fails" = 0 ] && echo "lint-edited: all passed"
exit "$fails"
