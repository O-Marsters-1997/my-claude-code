#!/usr/bin/env bash
set -u
HOOK="$(cd "$(dirname "$0")" && pwd)/require-sql-skills.sh"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
fails=0

mkdir -p "$TMP/db/vendor/x"
printf 'select 1;\n' >"$TMP/db/a.sql"
printf 'select 1;\n' >"$TMP/db/vendor/x/x.sql"
printf -- '-- Code generated by sqlc. DO NOT EDIT.\nselect 1;\n' >"$TMP/db/gen.sql"

skill_call() { printf '{"message":{"role":"assistant","content":[{"type":"tool_use","name":"Skill","input":{"skill":"%s"}}]}}\n' "$1"; }
slash_cmd() { printf '{"message":{"role":"user","content":"<command-name>/%s</command-name>"}}\n' "$1"; }

T_NONE="$TMP/none.jsonl"
T_MENTION="$TMP/mention.jsonl"
T_PG="$TMP/pg.jsonl"
T_SLASH="$TMP/slash.jsonl"
T_OTHER="$TMP/other.jsonl"
: >"$T_NONE"
printf '{"message":{"role":"user","content":"remember postgres-best-practices"}}\n' >"$T_MENTION"
skill_call postgres-best-practices >"$T_PG"
slash_cmd postgres-best-practices >"$T_SLASH"
skill_call go-idiomatic >"$T_OTHER"

payload() {
	jq -nc --arg f "$1" --arg t "$2" --arg tool "${3:-Edit}" \
		'{tool_name: $tool, tool_input: {file_path: $f, content: "select 1;\n"}, transcript_path: $t}'
}

check() {
	local name=$1 want=$2 input=$3
	shift 3
	local err code
	err=$(env "$@" "$HOOK" <<<"$input" 2>&1 >/dev/null)
	code=$?
	if [ "$code" != "$want" ]; then
		printf 'FAIL %s: exit %s, want %s\n%s\n' "$name" "$code" "$want" "$err"
		fails=$((fails + 1))
	fi
}

T_PARENT="$TMP/parent.jsonl"
mkdir -p "$TMP/parent/subagents"
skill_call postgres-best-practices >"$T_PARENT"
skill_call postgres-best-practices >"$TMP/parent/subagents/agent-loaded.jsonl"
: >"$TMP/parent/subagents/agent-bare.jsonl"

agent_payload() {
	jq -nc --arg f "$1" --arg t "$2" --arg a "$3" \
		'{tool_name: "Edit", tool_input: {file_path: $f}, transcript_path: $t, agent_id: $a}'
}

check "non-SQL file is ignored" 0 "$(payload "$TMP/db/README.md" "$T_NONE")" X=1
check "SQL file with no skill loaded blocks" 2 "$(payload "$TMP/db/a.sql" "$T_NONE")" X=1
check "mentioning the skill by name does not count" 2 "$(payload "$TMP/db/a.sql" "$T_MENTION")" X=1
check "a different skill does not count" 2 "$(payload "$TMP/db/a.sql" "$T_OTHER")" X=1
check "Skill tool call unblocks" 0 "$(payload "$TMP/db/a.sql" "$T_PG")" X=1
check "slash command unblocks" 0 "$(payload "$TMP/db/a.sql" "$T_SLASH")" X=1
check "Write is gated like Edit" 2 "$(payload "$TMP/db/a.sql" "$T_NONE" Write)" X=1
check "generated file is skipped" 0 "$(payload "$TMP/db/gen.sql" "$T_NONE")" X=1
check "vendor is skipped" 0 "$(payload "$TMP/db/vendor/x/x.sql" "$T_NONE")" X=1
check "opt-out env is honoured" 0 "$(payload "$TMP/db/a.sql" "$T_NONE")" CC_SQL_SKILLS_OFF=1
check "missing transcript fails open" 0 "$(payload "$TMP/db/a.sql" "$TMP/absent.jsonl")" X=1
check "malformed input fails open" 0 "not json" X=1
check "subagent that loaded the skill unblocks" 0 "$(agent_payload "$TMP/db/a.sql" "$T_PARENT" loaded)" X=1
check "subagent without the skill blocks even if the parent loaded it" 2 "$(agent_payload "$TMP/db/a.sql" "$T_PARENT" bare)" X=1
check "subagent with no transcript fails open" 0 "$(agent_payload "$TMP/db/a.sql" "$T_PARENT" absent)" X=1

new_write=$(jq -nc --arg f "$TMP/db/new_gen.sql" --arg t "$T_NONE" \
	'{tool_name: "Write", tool_input: {file_path: $f, content: "-- Code generated by x. DO NOT EDIT.\nselect 1;\n"}, transcript_path: $t}')
check "new generated file via Write is skipped" 0 "$new_write" X=1

msg=$("$HOOK" <<<"$(payload "$TMP/db/a.sql" "$T_NONE")" 2>&1 >/dev/null)
case "$msg" in
*postgres-best-practices*) ;;
*)
	printf 'FAIL deny message lacks skill name: %s\n' "$msg"
	fails=$((fails + 1))
	;;
esac

[ "$fails" -eq 0 ] && echo "all hook tests passed"
exit "$fails"
