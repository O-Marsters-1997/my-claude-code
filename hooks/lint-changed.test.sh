#!/usr/bin/env bash
set -u
HOOK="$(cd "$(dirname "$0")" && pwd)/lint-changed.sh"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
fails=0
BIOME=$(command -v biome)
HAS_GO=$(command -v golangci-lint)

check() {
	local name=$1 want=$2 cwd=$3 active=$4
	shift 4
	local err code
	err=$(jq -nc --arg c "$cwd" --argjson a "$active" '{hook_event_name: "Stop", cwd: $c, stop_hook_active: $a}' | env "$@" "$HOOK" 2>&1 >/dev/null)
	code=$?
	if [ "$code" != "$want" ]; then
		printf 'FAIL %s: exit %s, want %s\n%s\n' "$name" "$code" "$want" "$err"
		fails=$((fails + 1))
	fi
}

repo() {
	local r="$TMP/$1"
	mkdir -p "$r/svc/a" "$r/web/src" "$r/web/node_modules/.bin"
	printf 'module example.com/m\n\ngo 1.22\n' >"$r/svc/go.mod"
	printf 'package a\n\nfunc Add(a, b int) int { return a + b }\n\nfunc oldDead() {}\n' >"$r/svc/a/a.go"
	printf '{"linter":{"rules":{"correctness":{"noUnusedImports":"error"}}}}\n' >"$r/web/biome.json"
	printf 'export const x = 1;\n' >"$r/web/src/ok.ts"
	printf 'node_modules/\n' >"$r/.gitignore"
	[ -n "$BIOME" ] && ln -s "$BIOME" "$r/web/node_modules/.bin/biome"
	git -C "$r" init -q && git -C "$r" add -A && git -C "$r" -c user.name=t -c user.email=t@t commit -qm init
	echo "$r"
}

mkdir -p "$TMP/plain"
check "outside git passes" 0 "$TMP/plain" false X=1

R=$(repo clean)
check "clean tree passes" 0 "$R" false X=1

R=$(repo oldissue)
printf 'package a\n\nfunc Sub(a, b int) int { return a - b }\n' >"$R/svc/a/b.go"
[ -n "$HAS_GO" ] && check "issue committed before this turn is ignored" 0 "$R" false X=1

R=$(repo godead)
printf 'package a\n\nfunc newDead() {}\n' >"$R/svc/a/dead.go"
if [ -n "$HAS_GO" ]; then
	check "new unused Go func blocks" 2 "$R" false X=1
	check "second stop in a turn passes" 0 "$R" true X=1
	check "opt-out env skips" 0 "$R" false CC_LINT_CHANGED_OFF=1
fi

R=$(repo gogen)
printf '// Code generated by sqlc. DO NOT EDIT.\npackage a\n\nfunc genDead() {}\n' >"$R/svc/a/gen.go"
[ -n "$HAS_GO" ] && check "generated Go file passes" 0 "$R" false X=1

R=$(repo tsbad)
printf 'import { x } from "./ok";\nexport const z = 1;\n' >"$R/web/src/bad.ts"
if [ -n "$BIOME" ]; then
	check "unused TS import blocks" 2 "$R" false X=1
	rm "$R/web/biome.json"
	check "TS without biome.json passes" 0 "$R" false X=1
else
	echo "skip Biome cases: biome not on PATH"
fi

R=$(repo nobiome)
rm -f "$R/web/node_modules/.bin/biome"
printf 'import { x } from "./ok";\nexport const z = 1;\n' >"$R/web/src/bad.ts"
check "TS without installed biome passes" 0 "$R" false X=1

[ -z "$HAS_GO" ] && echo "skip Go cases: golangci-lint not installed"
[ "$fails" = 0 ] && echo "lint-changed: all passed"
exit "$fails"
