#!/usr/bin/env bash
# Run: hooks/check-written-comments.test.sh
set -u
HOOK="$(cd "$(dirname "$0")" && pwd)/check-written-comments.sh"
fails=0

edit() { jq -nc --arg f "$1" --arg n "$2" --arg o "${3:-}" '{tool_name:"Edit",tool_input:{file_path:$f,old_string:$o,new_string:$n}}'; }
write() { jq -nc --arg f "$1" --arg c "$2" '{tool_name:"Write",tool_input:{file_path:$f,content:$c}}'; }

expect() {
	local want="$1" name="$2" payload="$3"
	"$HOOK" <<<"$payload" >/dev/null 2>&1
	local got=$?
	if [ "$got" -ne "$want" ]; then
		echo "FAIL: $name (want $want, got $got)"
		fails=$((fails + 1))
	fi
}

expect 2 "go line comment" "$(edit /r/a.go $'x := 1\n// sets x')"
expect 2 "go block comment" "$(edit /r/a.go $'/* sets x */\nx := 1')"
expect 2 "go block continuation" "$(edit /r/a.go $'/*\n * sets x\n */')"
expect 2 "ts comment" "$(edit /r/a.ts $'// sets x\nconst x = 1')"
expect 2 "tsx jsx comment" "$(edit /r/a.tsx $'{/* header */}')"
expect 2 "python comment" "$(edit /r/a.py $'# sets x\nx = 1')"
expect 2 "shell comment" "$(edit /r/a.sh $'# do it\nls')"
expect 2 "yaml comment" "$(edit /r/a.yml $'# note\nkey: v')"
expect 2 "sql comment" "$(edit /r/a.sql $'-- note\nselect 1;')"
expect 2 "css comment" "$(edit /r/a.css $'/* note */\na { b: c }')"
expect 2 "html comment" "$(edit /r/a.html $'<!-- note -->\n<div></div>')"
expect 2 "dockerfile comment" "$(edit /r/Dockerfile $'# note\nFROM x')"
expect 2 "suppression is debt" "$(edit /r/a.ts $'// @ts-ignore\nx()')"
expect 2 "nolint is debt" "$(edit /r/a.go $'//nolint:errcheck\nx()')"
expect 2 "multiedit" "$(jq -nc '{tool_name:"MultiEdit",tool_input:{file_path:"/r/a.go",edits:[{old_string:"a",new_string:"// c\na"}]}}')"
expect 2 "write new file" "$(write /r/new.go $'package a\n// note\nfunc F() {}')"

expect 0 "no comment" "$(edit /r/a.go $'x := 1')"
expect 0 "unchanged comment kept" "$(edit /r/a.go $'// keep\nx := 2' $'// keep\nx := 1')"
expect 0 "go directive" "$(edit /r/a.go $'//go:generate mockgen\n//go:build linux')"
expect 0 "prettier-ignore" "$(edit /r/a.ts $'// prettier-ignore\nx()')"
expect 0 "shebang" "$(edit /r/a.sh $'#!/usr/bin/env bash\nls')"
expect 0 "sqlc name directive" "$(edit /r/q.sql $'-- name: GetJob :one\nselect 1;')"
expect 0 "licence header" "$(edit /r/a.go $'// Copyright 2026 Acme')"
expect 0 "linked constraint" "$(edit /r/a.go $'// Stripe rounds up: https://example.com/issue/1')"
expect 0 "generated header" "$(write /r/a.go $'// Code generated by sqlc. DO NOT EDIT.\n// versions:\npackage a')"
expect 0 "sqlc path" "$(edit /r/store/sqlc/a.go $'// note')"
expect 0 "snapshot path" "$(edit /r/snapshots/a.ts $'// note')"
expect 0 "node_modules" "$(edit /r/node_modules/x/a.js $'// note')"
expect 0 "markdown ignored" "$(edit /r/a.md $'# Heading')"
expect 0 "json ignored" "$(edit /r/a.json $'{}')"
expect 0 "hash in go string" "$(edit /r/a.go $'s := "# not a comment"')"
expect 0 "trailing comment is out of scope" "$(edit /r/a.go $'x := 1 // trailing')"
expect 0 "non-edit tool" "$(jq -nc '{tool_name:"Read",tool_input:{file_path:"/r/a.go"}}')"
expect 0 "no file path" "$(jq -nc '{tool_name:"Edit",tool_input:{}}')"

[ "$fails" -eq 0 ] && echo "all passed" || { echo "$fails failed"; exit 1; }
